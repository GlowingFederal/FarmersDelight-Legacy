    public static Item find(String name) {
        if(name.startsWith("farmersdelight:")) return Content.ITEMS.get(name.substring("farmersdelight:".length()));
        Item known=VANILLA.get(name); if(known!=null) return known;
        String[] parts=name.split(":",2); return parts.length==2 ? GameRegistry.findItem(parts[0],parts[1]) : null;
    }
    public static String name(Item item) {
        if(item==null) return "";
        String known=NAMES.get(item); if(known!=null) return known;
        for(Map.Entry<String,Item> entry:Content.ITEMS.entrySet()) if(entry.getValue()==item) { known="farmersdelight:"+entry.getKey();NAMES.put(item,known);return known; }
        GameRegistry.UniqueIdentifier id=GameRegistry.findUniqueIdentifierFor(item); return id==null ? "" : id.toString();
    }
    public static String name(Block block) { if(block==null) return "minecraft:air";String name=BLOCK_NAMES.get(block);return name!=null ? name : name(item(block)); }
    public static Block block(String name) {
        Block known=BLOCKS.get(name); if(known!=null) return known;
        if(name.startsWith("farmersdelight:")) return LegacyIds.findBlock(name.substring("farmersdelight:".length()));
        Item item=find(name); return item==null || item.itemID>=Block.blocksList.length ? null : Block.blocksList[item.itemID];
    }
